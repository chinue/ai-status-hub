export function makeT(locale: Locale) {
  return (key: string, ...params: Array<string | number>): string => {
    let template = dict[locale]?.[key] ?? dict['en']?.[key] ?? key;
    params.forEach((p, i) => {
      template = template.replace(`{${i}}`, String(p));
    });
    return template;
  };
}
